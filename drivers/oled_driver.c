void oled_show_text(u8 row, u8 col, const char* text, u8 font_size)
{
    if (text == NULL || font_size != 16) return;

    u8 page = row;
    u8 x    = col;

    while (*text) {
        char c = *text++;
        if (c < 32 || c > 126) c = ' ';
        u8 idx = c - 32;

        for (u8 i = 0; i < 6 && x < OLED_WIDTH; i++) {
            oled_buffer[page * OLED_WIDTH + x] = font_6x8[idx][i];
            x++;
        }
        /* 字符间距 */
        if (x < OLED_WIDTH) {
            oled_buffer[page * OLED_WIDTH + x] = 0x00;
            x++;
        }
    }
}

void oled_display_time_value(const char* time_str, const char* value_str)
{
    oled_clear_screen();
    oled_show_text(0, 0, time_str, 16);
    oled_show_text(1, 0, value_str, 16);
    oled_refresh();
}
